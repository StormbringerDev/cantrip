#!/usr/bin/env python3
"""Generate AST node definitions for the Cantrip interpreters."""

from __future__ import annotations

import argparse
from pathlib import Path

Field = tuple[str, str]
Node = tuple[str, list[Field]]

# Meta-types shared by every emitter. Add a field type here before using it
# in a node; each backend maps the name onto its own spelling.
TS_TYPES = {
    "Expr": "Expr",
    "Token": "Token",
    "LiteralValue": "LiteralValue",
}

C_TYPES = {
    "Expr": "Expr *",
    "Token": "Token",
    "LiteralValue": "LiteralValue",
}

EXPRESSIONS: list[Node] = [
    ("Binary", [("left", "Expr"), ("operator", "Token"), ("right", "Expr")]),
    ("Grouping", [("expression", "Expr")]),
    ("Literal", [("value", "LiteralValue")]),
    ("Unary", [("operator", "Token"), ("right", "Expr")]),
]


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Cantrip AST nodes.")
    parser.add_argument(
        "--target",
        required=True,
        choices=["ts", "c"],
        help="language to generate: ts or c",
    )
    parser.add_argument("outdir", type=Path, help="directory to write into")
    args = parser.parse_args()

    if args.outdir.exists() and not args.outdir.is_dir():
        parser.error(f"output path is not a directory: {args.outdir}")

    args.outdir.mkdir(parents=True, exist_ok=True)
    define_ast(args.outdir, "Expr", EXPRESSIONS, args.target)


def define_ast(
    output_dir: Path, base_name: str, nodes: list[Node], target: str
) -> None:
    """Write one base type (Expr, and later Stmt) for the selected target."""
    for _name, fields in nodes:
        for _field_name, type_name in fields:
            if type_name not in TS_TYPES or type_name not in C_TYPES:
                raise SystemExit(f"unknown AST field type: {type_name}")

    if target == "ts":
        text = emit_ts(base_name, nodes)
        filename = f"{base_name.lower()}.ts"
    elif target == "c":
        text = emit_c(base_name, nodes)
        filename = f"{base_name.lower()}.h"
    else:
        raise SystemExit(f"unknown target: {target}")

    (output_dir / filename).write_text(text, encoding="utf-8")


def emit_ts(base_name: str, nodes: list[Node]) -> str:
    lines = ["// Generated by tools/generate_ast.py. Do not edit.", ""]

    if uses_type(nodes, "Token"):
        lines.append('import type { Token } from "./token.js";')
        lines.append("")

    if uses_type(nodes, "LiteralValue"):
        lines.append("export type LiteralValue = string | number | boolean | null;")
        lines.append("")

    for name, fields in nodes:
        lines.append(f"export interface {name} {{")
        lines.append(f'  readonly type: "{name}";')
        for field_name, type_name in fields:
            lines.append(f"  readonly {field_name}: {TS_TYPES[type_name]};")
        lines.append("}")
        lines.append("")

    union = " | ".join(name for name, _fields in nodes)
    lines.append(f"export type {base_name} = {union};")
    lines.append("")

    for name, fields in nodes:
        params = ", ".join(
            f"{field_name}: {TS_TYPES[type_name]}" for field_name, type_name in fields
        )
        lines.append(f"export function {camel(name)}({params}): {name} {{")
        lines.extend(emit_ts_return(name, fields))
        lines.append("}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def emit_ts_return(name: str, fields: list[Field]) -> list[str]:
    props = ", ".join([f'type: "{name}"', *(field_name for field_name, _ in fields)])
    compact = f"  return {{ {props} }};"
    if len(compact) <= 80:
        return [compact]

    lines = ["  return {", f'    type: "{name}",']
    for field_name, _type_name in fields:
        lines.append(f"    {field_name},")
    lines.append("  };")
    return lines


def emit_c(base_name: str, nodes: list[Node]) -> str:
    guard = f"CANTRIP_{base_name.upper()}_H"
    lines = [
        "/* Generated by tools/generate_ast.py. Do not edit. */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
    ]

    if uses_type(nodes, "Token"):
        lines.append('#include "token.h"')
        lines.append("")

    if uses_type(nodes, "LiteralValue"):
        lines.append("#include <stdbool.h>")
        lines.append("#include <stddef.h>")
        lines.append("")

    # Node structs hold pointers to the base type, so the tag has to exist first.
    lines.append(f"typedef struct {base_name} {base_name};")
    lines.append("")
    lines.extend(emit_c_enum(f"{base_name.upper()}_", f"{base_name}Type", nodes))
    lines.append("")

    if uses_type(nodes, "LiteralValue"):
        lines.extend(emit_c_literal_value())
        lines.append("")

    for name, fields in nodes:
        lines.append("typedef struct {")
        for field_name, type_name in fields:
            lines.append(f"  {c_declarator(type_name, field_name)};")
        lines.append(f"}} {name}{base_name};")
        lines.append("")

    lines.append(f"struct {base_name} {{")
    lines.append(f"  {base_name}Type type;")
    lines.append("  union {")
    for name, _fields in nodes:
        lines.append(f"    {name}{base_name} {camel(name)};")
    lines.append("  } as;")
    lines.append("};")
    lines.append("")
    lines.append(f"#endif /* {guard} */")
    lines.append("")
    return "\n".join(lines)


def emit_c_enum(prefix: str, type_name: str, nodes: list[Node]) -> list[str]:
    lines = ["typedef enum {"]
    for name, _fields in nodes:
        lines.append(f"  {prefix}{name.upper()},")
    lines.append(f"}} {type_name};")
    return lines


def emit_c_literal_value() -> list[str]:
    return [
        "typedef enum {",
        "  LITERAL_NIL,",
        "  LITERAL_BOOL,",
        "  LITERAL_NUMBER,",
        "  LITERAL_STRING,",
        "} LiteralValueType;",
        "",
        "typedef struct {",
        "  LiteralValueType type;",
        "  union {",
        "    bool boolean;",
        "    double number;",
        "    struct {",
        "      const char *chars;",
        "      size_t length;",
        "    } string;",
        "  } as;",
        "} LiteralValue;",
    ]


def c_declarator(type_name: str, field_name: str) -> str:
    c_type = C_TYPES[type_name]
    if c_type.endswith("*"):
        return f"{c_type}{field_name}"
    return f"{c_type} {field_name}"


def uses_type(nodes: list[Node], type_name: str) -> bool:
    return any(
        field_type == type_name
        for _name, fields in nodes
        for _field, field_type in fields
    )


def camel(name: str) -> str:
    return name[:1].lower() + name[1:]


if __name__ == "__main__":
    main()
